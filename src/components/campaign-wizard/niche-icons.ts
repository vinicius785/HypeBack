export const normName = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .trim();

/** Ícone do nicho pelo nome (ex.: "Alimentação & Bebidas" -> talheres), ou `null` quando não há regra para ele. */
export function nicheIconFor(name: string): string | null {
  const n = normName(name);
  const hit = RULES.find(([re]) => re.test(n));
  return hit ? PATHS[hit[1]] : null;
}
